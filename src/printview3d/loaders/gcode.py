"""G-code toolpath parser.

Reads a G-code file and turns it into line segments that can be drawn in 3D.
Each segment remembers which layer it belongs to and what kind of feature
it is (outer wall, infill, support, travel, ...), so the viewer can colour
them and step through the print layer by layer.

Tested against output from Creality Print 6 / OrcaSlicer, PrusaSlicer and
Cura. Other slicers work too; they just may show everything as "Other"
if they do not write feature comments.
"""

from __future__ import annotations

import base64
import math
import re
from array import array
from dataclasses import dataclass, field
from typing import Callable, Optional

import numpy as np

# --------------------------------------------------------------------------
# Feature types: (key, label shown in the UI, colour)
# The order here is the order the checkboxes appear in.
# --------------------------------------------------------------------------
FEATURES: list[tuple[str, str, str]] = [
    ("outer_wall",        "Outer wall",          "#ff8a3d"),
    ("inner_wall",        "Inner wall",          "#ffd23f"),
    ("overhang",          "Overhang wall",       "#3d6fd1"),
    ("infill",            "Sparse infill",       "#d6453d"),
    ("solid_infill",      "Solid infill",        "#a855f7"),
    ("top_bottom",        "Top / bottom",        "#f06595"),
    ("bridge",            "Bridge",              "#4dabf7"),
    ("gap_fill",          "Gap fill",            "#f1f3f5"),
    ("ironing",           "Ironing",             "#ffa8a8"),
    ("support",           "Support",             "#40c057"),
    ("support_interface", "Support interface",   "#2b8a3e"),
    ("skirt_brim",        "Skirt / brim",        "#22b8cf"),
    ("prime_tower",       "Prime tower",         "#868e96"),
    ("other",             "Other / custom",      "#adb5bd"),
    ("travel",            "Travel moves",        "#5c7cfa"),
]
FEATURE_INDEX = {key: i for i, (key, _, _) in enumerate(FEATURES)}
TRAVEL = FEATURE_INDEX["travel"]
OTHER = FEATURE_INDEX["other"]


def classify_feature(name: str) -> int:
    """Map a slicer's ;TYPE: comment to one of our feature categories."""
    n = name.strip().lower().replace("_", " ").replace("-", " ")
    if "outer" in n or "external perimeter" in n:
        key = "outer_wall"
    elif "overhang" in n:
        key = "overhang"
    elif "ironing" in n:
        key = "ironing"
    elif "support" in n and "interface" in n:
        key = "support_interface"
    elif "support" in n:
        key = "support"
    elif "bridge" in n:
        key = "bridge"
    elif "gap" in n:
        key = "gap_fill"
    elif "wall" in n or "perimeter" in n:
        key = "inner_wall"
    elif "top" in n or "bottom" in n or "skin" in n:
        key = "top_bottom"
    elif "solid" in n:
        key = "solid_infill"
    elif "infill" in n or "fill" in n:
        key = "infill"
    elif "skirt" in n or "brim" in n:
        key = "skirt_brim"
    elif "prime" in n or "tower" in n:
        key = "prime_tower"
    else:
        key = "other"
    return FEATURE_INDEX[key]


# --------------------------------------------------------------------------
# Metadata patterns (matched against comment lines)
# --------------------------------------------------------------------------
_META_PATTERNS: list[tuple[str, re.Pattern]] = [
    ("Slicer",          re.compile(r"^\s*(?:generated by|generated with)\s+(.+)$", re.I)),
    ("Print time",      re.compile(r"estimated printing time(?: \(normal mode\))?\s*[=:]\s*(.+)$", re.I)),
    ("Print time",      re.compile(r"^\s*model printing time:\s*([^;]+)", re.I)),
    ("_cura_time",      re.compile(r"^TIME:(\d+)\s*$")),
    ("Filament (g)",    re.compile(r"^\s*total filament used \[g\]\s*=\s*(.+)$", re.I)),
    ("Filament (g)",    re.compile(r"^\s*filament used \[g\]\s*=\s*(.+)$", re.I)),
    ("Filament (mm)",   re.compile(r"^\s*filament used \[mm\]\s*=\s*(.+)$", re.I)),
    ("_cura_filament",  re.compile(r"^Filament used:\s*([\d.]+)m", re.I)),
    ("Filament type",   re.compile(r"^\s*filament_type\s*=\s*(.+)$", re.I)),
    ("Layer height",    re.compile(r"^\s*layer_height\s*=\s*(.+)$", re.I)),
    ("Nozzle",          re.compile(r"^\s*nozzle_diameter\s*=\s*(.+)$", re.I)),
    ("Printer",         re.compile(r"^\s*printer_model\s*=\s*(.+)$", re.I)),
    ("Printer profile", re.compile(r"^\s*printer_settings_id\s*=\s*(.+)$", re.I)),
    ("_bed",            re.compile(r"^\s*(?:printable_area|bed_shape)\s*=\s*(.+)$", re.I)),
]

# "thumbnail begin 300x300 1234" (PrusaSlicer, OrcaSlicer, ...); Creality Print writes the size as
# "300*300" (png / jpg blocks for its printers' screens) or "300 300" (thumbnail block).
_THUMB_BEGIN = re.compile(r"^\s*(thumbnail|thumbnail_png|thumbnail_jpg|png|jpg|jpeg)\s+begin\s+(\d+)\s*(?:[x*]\s*|\s+)(\d+)", re.I)


def parse_bed_shape(value) -> Optional[tuple[float, float, float, float]]:
    """Parse 'printable_area' / 'bed_shape' (e.g. '0x0,350x0,350x350,0x350').

    Accepts either a comma-separated string or a list of 'XxY' strings
    (the 3MF project config stores it as a JSON list).
    Returns (xmin, xmax, ymin, ymax) or None.
    """
    try:
        if isinstance(value, str):
            parts = [p for p in value.replace('"', "").split(",") if p.strip()]
        else:
            parts = list(value)
        pts = []
        for p in parts:
            x, y = str(p).strip().lower().split("x")
            pts.append((float(x), float(y)))
        if len(pts) < 3:
            return None
        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        if max(xs) - min(xs) < 10 or max(ys) - min(ys) < 10:
            return None
        return (min(xs), max(xs), min(ys), max(ys))
    except (ValueError, TypeError):
        return None


def _format_seconds(sec: float) -> str:
    sec = int(sec)
    d, rem = divmod(sec, 86400)
    h, rem = divmod(rem, 3600)
    m, s = divmod(rem, 60)
    out = []
    if d:
        out.append(f"{d}d")
    if h or d:
        out.append(f"{h}h")
    out.append(f"{m}m")
    if not d and not h:
        out.append(f"{s}s")
    return " ".join(out)


# --------------------------------------------------------------------------
# Result container
# --------------------------------------------------------------------------
@dataclass
class GcodeData:
    starts: np.ndarray            # (N, 3) float32 segment start points
    ends: np.ndarray              # (N, 3) float32 segment end points
    types: np.ndarray             # (N,)  uint8   feature index (FEATURES)
    layers: np.ndarray            # (N,)  int32   layer index, non-decreasing
    layer_z: np.ndarray           # (L,)  float32 Z height per layer
    layer_end: np.ndarray         # (L,)  int64   index after the last segment of each layer
    meta: dict = field(default_factory=dict)       # human-readable info
    bed: Optional[tuple] = None                    # (xmin, xmax, ymin, ymax)
    thumbnail: Optional[bytes] = None              # PNG/JPEG bytes
    extrusion_bounds: Optional[tuple] = None       # (xmin,xmax,ymin,ymax,zmin,zmax)
    feature_counts: dict = field(default_factory=dict)

    @property
    def n_layers(self) -> int:
        return int(len(self.layer_z))

    @property
    def n_segments(self) -> int:
        return int(len(self.types))


# --------------------------------------------------------------------------
# Parser
# --------------------------------------------------------------------------
THUMBNAIL_HEAD = 4 * 1024 * 1024       # slicers write the pictures at the top: this much is read


def read_thumbnail(path: str, limit: int = THUMBNAIL_HEAD) -> Optional[bytes]:
    """The largest preview picture in a G-code file's header, without reading the toolpath.
    Slicers write the pictures at the top, so only the first `limit` bytes are read."""
    with open(path, "rb") as f:
        return thumbnail_from_head(f.read(limit))


def thumbnail_from_head(raw_head: bytes) -> Optional[bytes]:
    """The largest preview picture in the first part of a G-code file (also one inside a ZIP)."""
    head = raw_head.decode("utf-8", errors="replace")
    best: tuple[int, bytes] | None = None
    word, size, buf = None, 0, []
    for raw in head.splitlines():
        sc = raw.find(";")
        if sc < 0:
            if word is None and raw.strip():
                # The first move: the pictures are all above it.
                if raw.lstrip()[:2] in ("G0", "G1", "G2", "G3"):
                    break
            continue
        c = raw[sc + 1:].strip()
        if word is not None:
            if c.lower().startswith(word + " end"):
                try:
                    data = base64.b64decode("".join(buf))
                    if (data[:8] == b"\x89PNG\r\n\x1a\n" or data[:3] == b"\xff\xd8\xff") and (
                            best is None or size > best[0]):
                        best = (size, data)
                except Exception:
                    pass
                word, buf = None, []
            else:
                buf.append(c)
            continue
        m = _THUMB_BEGIN.match(c)
        if m:
            word, size, buf = m.group(1).lower(), int(m.group(2)) * int(m.group(3)), []
    return best[1] if best else None


def parse_gcode_file(path: str, progress: Optional[Callable[[float], None]] = None) -> GcodeData:
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()
    return parse_gcode_text(text, progress)


def parse_gcode_text(text: str, progress: Optional[Callable[[float], None]] = None) -> GcodeData:
    lines = text.splitlines()
    n_lines = len(lines)

    # Prefer explicit layer markers when the slicer writes them.
    use_markers = (";LAYER_CHANGE" in text) or (";LAYER:" in text)

    pts = array("f")       # x0 y0 z0 x1 y1 z1 per segment
    types = array("B")
    layers = array("i")
    layer_z: dict[int, float] = {}

    x = y = z = 0.0
    e = 0.0
    abs_xyz = True
    abs_e = True
    feature = OTHER
    layer = 0
    marker_count = 0
    last_layer_z: Optional[float] = None
    layer_z_pending = False
    total_extruded = 0.0

    meta: dict[str, str] = {}
    bed = None
    thumbs: list[tuple[int, bytes]] = []
    thumb_word = None
    thumb_size = 0
    thumb_buf: list[str] = []

    feature_cache: dict[str, int] = {}

    def add_segment(nx, ny, nz, extruding: bool):
        nonlocal last_layer_z, layer, layer_z_pending
        if extruding:
            if not use_markers:
                if last_layer_z is None:
                    last_layer_z = nz
                elif nz > last_layer_z + 1e-4:
                    layer += 1
                    last_layer_z = nz
            if layer_z_pending or layer not in layer_z:
                layer_z[layer] = nz
                layer_z_pending = False
            t = feature
        else:
            t = TRAVEL
        pts.extend((x, y, z, nx, ny, nz))
        types.append(t)
        layers.append(layer)

    step = max(1, n_lines // 100)

    for li, raw in enumerate(lines):
        if progress is not None and li % step == 0:
            progress(li / max(1, n_lines))
        if not raw:
            continue

        # ---------------- comments ----------------
        sc = raw.find(";")
        if sc >= 0:
            comment = raw[sc + 1:]
            code = raw[:sc].strip()

            if thumb_word is not None:
                c = comment.strip()
                if c.lower().startswith(thumb_word + " end"):
                    try:
                        data = base64.b64decode("".join(thumb_buf))
                        if data[:8] == b"\x89PNG\r\n\x1a\n" or data[:3] == b"\xff\xd8\xff":
                            thumbs.append((thumb_size, data))
                    except Exception:
                        pass
                    thumb_word = None
                    thumb_buf = []
                else:
                    thumb_buf.append(c)
                continue

            if not code:
                c = comment.lstrip()
                if c.startswith("TYPE:"):
                    tname = c[5:].strip()
                    f_idx = feature_cache.get(tname)
                    if f_idx is None:
                        f_idx = classify_feature(tname)
                        feature_cache[tname] = f_idx
                    feature = f_idx
                elif c.startswith("LAYER_CHANGE") or c.startswith("LAYER:"):
                    if use_markers:
                        marker_count += 1
                        layer = max(0, marker_count - 1)
                        layer_z_pending = True
                elif "=" in c or ":" in c or "begin" in c or "enerated" in c:
                    m = _THUMB_BEGIN.match(c)
                    if m:
                        thumb_word = m.group(1).lower()
                        thumb_size = int(m.group(2)) * int(m.group(3))
                        thumb_buf = []
                        continue
                    for key, pat in _META_PATTERNS:
                        if key in meta:
                            continue
                        mm = pat.search(c)
                        if mm:
                            meta[key] = mm.group(1).strip()
                            break
                continue
        else:
            code = raw.strip()
            if not code:
                continue

        # ---------------- commands ----------------
        parts = code.split()
        cmd = parts[0].upper()
        if cmd[0] == "N" and len(parts) > 1:      # line numbers: "N12 G1 X.."
            parts = parts[1:]
            cmd = parts[0].upper()

        if cmd in ("G1", "G0", "G2", "G3"):
            px = py = pz = pe = None
            pi = pj = 0.0
            for p in parts[1:]:
                if not p:
                    continue
                letter = p[0].upper()
                try:
                    val = float(p[1:])
                except ValueError:
                    continue
                if letter == "X":
                    px = val
                elif letter == "Y":
                    py = val
                elif letter == "Z":
                    pz = val
                elif letter == "E":
                    pe = val
                elif letter == "I":
                    pi = val
                elif letter == "J":
                    pj = val

            if abs_xyz:
                nx = x if px is None else px
                ny = y if py is None else py
                nz = z if pz is None else pz
            else:
                nx = x + (px or 0.0)
                ny = y + (py or 0.0)
                nz = z + (pz or 0.0)

            de = 0.0
            if pe is not None:
                if abs_e:
                    de = pe - e
                    e = pe
                else:
                    de = pe
                    e += pe

            moved = (nx != x) or (ny != y) or (nz != z)
            if not moved:
                continue
            extruding = de > 1e-7 and ((nx != x) or (ny != y))
            if extruding:
                total_extruded += de

            if cmd in ("G2", "G3") and (pi or pj):
                # Arc: approximate with short straight chords.
                cx, cy = x + pi, y + pj
                r = math.hypot(x - cx, y - cy)
                a0 = math.atan2(y - cy, x - cx)
                a1 = math.atan2(ny - cy, nx - cx)
                if cmd == "G2":          # clockwise
                    sweep = a1 - a0
                    if sweep >= -1e-9:
                        sweep -= 2 * math.pi
                else:                    # counter-clockwise
                    sweep = a1 - a0
                    if sweep <= 1e-9:
                        sweep += 2 * math.pi
                n_seg = max(2, min(128, int(abs(sweep) * r / 0.8) + 1))
                sz = z
                for k in range(1, n_seg + 1):
                    t = k / n_seg
                    ax = cx + r * math.cos(a0 + sweep * t)
                    ay = cy + r * math.sin(a0 + sweep * t)
                    az = sz + (nz - sz) * t
                    if k == n_seg:
                        ax, ay = nx, ny
                    add_segment(ax, ay, az, extruding)
                    x, y, z = ax, ay, az
            else:
                add_segment(nx, ny, nz, extruding)
            x, y, z = nx, ny, nz

        elif cmd == "G90":
            # Follows Klipper (used by Creality K-series printers): G90/G91 only
            # affect X/Y/Z. Slicers always set E mode explicitly with M82/M83.
            abs_xyz = True
        elif cmd == "G91":
            abs_xyz = False
        elif cmd == "M82":
            abs_e = True
        elif cmd == "M83":
            abs_e = False
        elif cmd == "G92":
            for p in parts[1:]:
                if not p:
                    continue
                letter = p[0].upper()
                try:
                    val = float(p[1:])
                except ValueError:
                    continue
                if letter == "E":
                    e = val
                elif letter == "X":
                    x = val
                elif letter == "Y":
                    y = val
                elif letter == "Z":
                    z = val
        elif cmd == "G28":
            # Homing: treat as moving to 0 on the given (or all) axes.
            axes = {p[0].upper() for p in parts[1:] if p}
            if not axes & {"X", "Y", "Z"}:
                x = y = z = 0.0
            else:
                if "X" in axes:
                    x = 0.0
                if "Y" in axes:
                    y = 0.0
                if "Z" in axes:
                    z = 0.0

    if progress is not None:
        progress(1.0)

    # ---------------- build arrays ----------------
    seg = np.frombuffer(pts, dtype=np.float32).reshape(-1, 6) if len(pts) else np.zeros((0, 6), np.float32)
    starts = np.ascontiguousarray(seg[:, 0:3])
    ends = np.ascontiguousarray(seg[:, 3:6])
    t_arr = np.frombuffer(types, dtype=np.uint8).copy() if len(types) else np.zeros(0, np.uint8)
    l_arr = np.frombuffer(layers, dtype=np.int32).copy() if len(layers) else np.zeros(0, np.int32)

    n_layers = int(l_arr.max()) + 1 if len(l_arr) else 0
    lz = np.full(n_layers, np.nan, dtype=np.float32)
    for k, v in layer_z.items():
        if k < n_layers:
            lz[k] = v
    # Fill gaps (layers with travel only) from the previous layer.
    last = 0.0
    for k in range(n_layers):
        if np.isnan(lz[k]):
            lz[k] = last
        else:
            last = lz[k]
    layer_end = np.searchsorted(l_arr, np.arange(n_layers), side="right").astype(np.int64)

    # Bounds of the actual printed material (ignores travel / homing moves)
    # Prefer real model features: skip travel and "other" (purge lines, wipes)
    ext_mask = (t_arr != TRAVEL) & (t_arr != OTHER)
    if not ext_mask.any():
        ext_mask = t_arr != TRAVEL
    ext_bounds = None
    if ext_mask.any():
        p = np.vstack([starts[ext_mask], ends[ext_mask]])
        mn, mx = p.min(axis=0), p.max(axis=0)
        ext_bounds = (float(mn[0]), float(mx[0]), float(mn[1]), float(mx[1]), float(mn[2]), float(mx[2]))

    counts = {}
    if len(t_arr):
        bc = np.bincount(t_arr, minlength=len(FEATURES))
        counts = {FEATURES[i][0]: int(c) for i, c in enumerate(bc) if c}

    # ---------------- tidy metadata ----------------
    if "_bed" in meta:
        bed = parse_bed_shape(meta.pop("_bed"))
    if "_cura_time" in meta:
        t = meta.pop("_cura_time")
        meta.setdefault("Print time", _format_seconds(float(t)))
    if "_cura_filament" in meta:
        meters = meta.pop("_cura_filament")
        meta.setdefault("Filament (mm)", f"{float(meters) * 1000:.0f}")
    meta = {k: v for k, v in meta.items() if not k.startswith("_")}
    if "Filament (mm)" not in meta and total_extruded > 0:
        meta["Filament (mm)"] = f"{total_extruded:.0f} (calculated)"

    thumb = max(thumbs, key=lambda t: t[0])[1] if thumbs else None

    return GcodeData(
        starts=starts, ends=ends, types=t_arr, layers=l_arr,
        layer_z=lz, layer_end=layer_end, meta=meta, bed=bed,
        thumbnail=thumb, extrusion_bounds=ext_bounds, feature_counts=counts,
    )
